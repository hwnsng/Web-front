import { test, expect } from '@playwright/test';
test('reset to zero, save ordered manual results, then re-register today match', async ({ page }) => {
  await page.goto('/loginPage');
  await page.getByLabel('아이디').fill('admin');
  await page.getByLabel('비밀번호', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('link', { name: '관리자', exact: true })).toBeVisible();
  const state = await (await page.request.get('/api/state')).json();
  expect((await page.request.put('/api/standings/2-1', { data: { total: 3, remaining: 8, win: 2, lose: 1 } })).ok()).toBeTruthy();
  const schedule = { date: state.today, time: '12:50', home: '2-1', away: '2-2' };
  const scheduled = await page.request.post('/api/matches', { data: schedule });
  expect(scheduled.ok()).toBeTruthy();
  const { id } = await scheduled.json();
  await page.goto('/rankPage');
  const row = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '2-1', exact: true }) });
  await page.getByRole('button', { name: '수정', exact: true }).click();
  for (let i = 0; i < 2; i++) await page.getByRole('button', { name: '2-1 승리 감소', exact: true }).click();
  await page.getByRole('button', { name: '2-1 패배 감소', exact: true }).click();
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: '2-1 경기 수 감소', exact: true }).click();
  await page.getByRole('button', { name: '저장', exact: true }).click();
  await expect(row.locator('.standings-played')).toHaveText('0');
  await page.goto('/todayMatchPage');
  await expect(page.getByLabel('2-1 최근 경기, 오른쪽이 최신').locator('.form-result')).toHaveText(['–', '–', '–', '–', '–']);
  await page.goto('/rankPage');
  await page.getByRole('button', { name: '수정', exact: true }).click();
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: '2-1 경기 수 증가', exact: true }).click();
  for (const name of ['승리', '패배', '패배']) await page.getByRole('button', { name: `2-1 ${name} 증가`, exact: true }).click();
  await page.getByRole('button', { name: '저장', exact: true }).click();
  await expect(row.locator('.standings-wins')).toHaveText('1');
  expect((await page.request.delete(`/api/matches/${id}`)).ok()).toBeTruthy();
  const reRegistered = await page.request.post('/api/matches', { data: schedule });
  expect(reRegistered.ok()).toBeTruthy();
  const { id: newId } = await reRegistered.json();
  await page.goto('/todayMatchPage');
  await expect(page.getByLabel('2-1 최근 경기, 오른쪽이 최신').locator('.form-result')).toHaveText(['–', '–', '승', '패', '패']);
  await page.reload();
  await expect(page.getByLabel('2-1 최근 경기, 오른쪽이 최신').locator('.form-result')).toHaveText(['–', '–', '승', '패', '패']);
  expect((await page.request.delete(`/api/matches/${newId}`)).ok()).toBeTruthy();
});
test('login failures show only the friendly message even when state cannot be fetched', async ({ page }) => {
  await page.route('**/api/state', route => route.abort('failed'));
  await page.route('**/api/login', route => route.fulfill({
    status: 403, contentType: 'application/json', body: JSON.stringify({ error: '허용되지 않은 요청입니다.' }),
  }));
  await page.goto('/loginPage');
  await page.getByLabel('아이디').fill('invalid');
  await page.getByLabel('비밀번호', { exact: true }).fill('invalid');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('정보가 잘못되었습니다.');
  await expect(page.locator('.server-error')).toHaveCount(0);
  await expect(page.getByText('허용되지 않은 요청입니다.')).toHaveCount(0);
  await page.route('**/api/login', route => route.abort('failed'));
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('정보가 잘못되었습니다.');
  await expect(page.getByText('Failed to fetch', { exact: false })).toHaveCount(0);
});
