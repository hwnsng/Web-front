import { test, expect } from '@playwright/test';

test('2025 archived standings stay isolated while current season results update', async ({ page }) => {
  await page.goto('/loginPage');
  await page.getByLabel('아이디').fill('admin');
  await page.getByLabel('비밀번호', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('button', { name: '로그아웃', exact: true })).toBeVisible();
  await page.goto('/rankPage');
  await expect(page.getByRole('tab', { name: '2026' })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('tab', { name: '2025' }).click();
  await expect(page.locator('.season-estimate-note')).toHaveCount(0);
  const archiveRows = page.locator('.standings-table tbody tr');
  await expect(archiveRows).toHaveCount(12);
  await expect(archiveRows.nth(0).getByRole('rowheader')).toHaveText('3-3');
  await expect(archiveRows.nth(1).getByRole('rowheader')).toHaveText('2-1');
  await expect(archiveRows.nth(0).locator('.standings-points')).toHaveText('63');
  await expect(archiveRows.nth(1).locator('.standings-points')).toHaveText('60');
  await expect(archiveRows.nth(0).locator('.standings-streak')).toHaveText('5승');
  await expect(archiveRows.nth(1).locator('.standings-streak')).toHaveText('3승');
  await expect(archiveRows.nth(4).getByRole('rowheader')).toHaveText('2-2');
  await expect(page.getByRole('button', { name: '수정', exact: true })).toHaveCount(0);
  const before = await archiveRows.allTextContents();
  await page.getByRole('tab', { name: '2026' }).click();
  await expect(page.getByRole('button', { name: '수정', exact: true })).toBeVisible();
  const state = await (await page.request.get('/api/state')).json();
  const created = await page.request.post('/api/matches', { data: { date: state.today, time: '12:50', home: '3-3', away: '3-4' } });
  expect(created.ok()).toBeTruthy();
  const { id } = await created.json();
  expect((await page.request.put(`/api/matches/${id}/result`, { data: { homeSets: 2, awaySets: 1 } })).ok()).toBeTruthy();
  await page.reload();
  const currentTeam = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '3-3', exact: true }) });
  await expect(currentTeam.locator('.standings-played')).toHaveText('1');
  await expect(currentTeam.locator('.standings-points')).toHaveText('6');
  await page.getByRole('tab', { name: '2025' }).click();
  expect(await archiveRows.allTextContents()).toEqual(before);
  await page.getByRole('tab', { name: '2025' }).press('ArrowRight');
  await expect(page.getByRole('tab', { name: '2026' })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: '수정', exact: true }).click();
  await expect(page.getByRole('tab', { name: '2025' })).toBeDisabled();
  await page.getByRole('button', { name: '취소', exact: true }).click();
});
